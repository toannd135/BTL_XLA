#!/usr/bin/env python3
"""Classify a reviewed segmentation batch as smoke, pilot, or evaluation ready."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

from PIL import Image

BASE = Path(__file__).resolve().parents[1]
SPLITS = {"train", "val", "test"}


def csv_rows(path: Path):
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def load_latest_events():
    latest = {}
    path = BASE / "review_history.jsonl"
    if path.exists():
        for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            event = json.loads(line)
            latest[event["polygon_id"]] = event
    return latest


def read_phash_mendeley_names():
    result = set()
    for row in csv_rows(BASE / "near_duplicate_candidates_full_dataset.csv"):
        for key in ("image_a", "image_b"):
            name = row[key]
            if name.startswith("mendeley_v1_"):
                result.add(name.removeprefix("mendeley_v1_"))
    return result


def verify_yolo_mask(path: Path, asset_id: str):
    errors = []
    if not path.is_file():
        return [f"missing label: {asset_id}"]
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
        if not lines:
            return [f"empty mask file: {asset_id}"]
        for line_no, line in enumerate(lines, 1):
            try:
                values = [float(x) for x in line.split()]
            except ValueError:
                errors.append(f"non-numeric mask: {asset_id} line {line_no}")
                continue
            coords = values[1:]
            if not values or values[0] != 0 or len(coords) < 6 or len(coords) % 2 or any(v < 0 or v > 1 for v in coords):
                errors.append(f"invalid segmentation row: {asset_id} line {line_no}")
    except OSError as exc:
        errors.append(f"unreadable label: {asset_id}: {exc}")
    return errors


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--batch", type=Path, required=True, help="Exported candidate batch directory")
    ap.add_argument("--assignments", type=Path, default=BASE / "pilot_split_manifest.csv",
                    help="Manually evidenced split/provenance assignments; never generated by this checker")
    ap.add_argument("--output", type=Path, default=BASE / "training_readiness_report.json")
    args = ap.parse_args()
    batch = args.batch.expanduser().resolve()
    manifest = csv_rows(batch / "candidate_manifest.csv")
    ai_assessments = {r.get("polygon_id", ""): r for r in csv_rows(batch / "ai_review_manifest.csv")}
    assignments = {r.get("asset_id", ""): r for r in csv_rows(args.assignments.expanduser().resolve())}
    latest = load_latest_events()
    queue = csv_rows(BASE / "review_queue.csv")
    queue_by_asset = defaultdict(list)
    for row in queue:
        queue_by_asset[row["asset_id"]].append(row)

    reviewed_polygons = sum(r["polygon_id"] in latest for r in queue)
    verified_green_polygons = sum(
        latest.get(r["polygon_id"], {}).get("decision") == "GREEN_APPLE"
        and latest.get(r["polygon_id"], {}).get("mask_valid") == "yes"
        and latest.get(r["polygon_id"], {}).get("image_quality_ok") == "yes"
        for r in queue)

    review_errors, image_errors, mask_errors = [], [], []
    ai_approved_polygons = 0
    human_reviewed_candidate_polygons = 0
    source_test_training_assets = []
    missing_assignments, split_evidence_errors, val_independence_errors = [], [], []
    family_evidence_warnings = []
    counts = {s: 0 for s in (*sorted(SPLITS), "exclude")}
    polygon_counts = {s: 0 for s in counts}
    families = {s: set() for s in SPLITS}
    family_splits = defaultdict(set)
    sha_splits = defaultdict(set)
    phash_names = read_phash_mendeley_names()
    phash_split_pairs = []
    candidate_by_name_split = defaultdict(list)

    for row in manifest:
        asset_id = row.get("asset_id", "")
        if row.get("source_split_original", "").strip().lower() == "test":
            source_test_training_assets.append(asset_id)
        image_rows = queue_by_asset.get(asset_id, [])
        polygon_ids = {r["polygon_id"] for r in image_rows}
        reviewed_ids = set()
        for pid in polygon_ids:
            event = latest.get(pid, {})
            assessment = ai_assessments.get(pid, {})
            human_ok = (event.get("decision") == "GREEN_APPLE" and event.get("mask_valid") == "yes"
                        and event.get("image_quality_ok") == "yes")
            ai_ok = (assessment.get("decision") == "AUTO_APPROVED"
                     and assessment.get("confidence_band") == "HIGH_UNCALIBRATED"
                     and assessment.get("human_verified") == "false")
            if human_ok:
                reviewed_ids.add(pid); human_reviewed_candidate_polygons += 1
            elif ai_ok:
                reviewed_ids.add(pid); ai_approved_polygons += 1
        if not polygon_ids or polygon_ids != reviewed_ids:
            review_errors.append(asset_id)

        image_path = batch / row.get("image_path", "")
        if not image_path.is_file():
            image_errors.append(f"missing image: {asset_id}")
        else:
            try:
                digest = hashlib.sha256(image_path.read_bytes()).hexdigest()
                if digest != row.get("image_sha256"):
                    image_errors.append(f"SHA-256 mismatch: {asset_id}")
                with Image.open(image_path) as im:
                    im.verify()
            except Exception as exc:
                image_errors.append(f"unreadable/integrity error: {asset_id}: {exc}")
        mask_errors.extend(verify_yolo_mask(batch / row.get("label_path", ""), asset_id))

        assignment = assignments.get(asset_id)
        if not assignment:
            missing_assignments.append(asset_id)
            continue
        split = assignment.get("dataset_split", "").strip().lower()
        if split not in SPLITS | {"exclude"}:
            missing_assignments.append(asset_id)
            continue
        counts[split] += 1
        polygon_counts[split] += int(row.get("polygon_count", 0) or 0)
        if split == "exclude":
            continue
        split_evidence = assignment.get("split_evidence", "").strip()
        if not split_evidence:
            split_evidence_errors.append(asset_id)
        if split == "val" and (assignment.get("independence_verified", "").strip().lower() != "yes"
                                or not assignment.get("independence_evidence", "").strip()):
            val_independence_errors.append(asset_id)

        family = assignment.get("source_family_id", "").strip()
        family_evidence = assignment.get("provenance_evidence", "").strip()
        if family and family_evidence:
            families[split].add(family)
            family_splits[family].add(split)
        else:
            family_evidence_warnings.append(asset_id)
        sha_splits[row.get("image_sha256", "")].add(split)
        source_name = f"train_{row.get('original_filename', '')}"
        if source_name in phash_names:
            phash_split_pairs.append({"asset_id": asset_id, "split": split, "source_image": row.get("original_filename", "")})
        candidate_by_name_split[(row.get("original_filename", ""), split)].append(asset_id)

    family_leaks = sorted(fid for fid, assigned_splits in family_splits.items() if len(assigned_splits) > 1)
    sha_cross_split = sorted(sha for sha, assigned_splits in sha_splits.items() if sha and len(assigned_splits) > 1)
    duplicate_sha_pairs = sum(max(0, n - 1) for n in Counter(r.get("image_sha256", "") for r in manifest if r.get("image_sha256")).values())
    train_val_images = counts["train"] + counts["val"]
    source_families_by_split = {s: len(families[s]) for s in sorted(SPLITS)}
    known_family_unverified = bool(family_evidence_warnings)

    smoke_blockers = []
    if not manifest: smoke_blockers.append("NO_REVIEWED_CANDIDATE_IMAGES")
    if review_errors: smoke_blockers.append("INCOMPLETE_HUMAN_GREEN_MASK_QUALITY_REVIEW")
    if image_errors: smoke_blockers.append("IMAGE_MISSING_UNREADABLE_OR_HASH_MISMATCH")
    if mask_errors: smoke_blockers.append("MASK_MISSING_EMPTY_OR_INVALID")
    if source_test_training_assets: smoke_blockers.append("SOURCE_TEST_IMAGE_IN_TRAINING_CANDIDATE")
    smoke_ready = not smoke_blockers

    pilot_blockers = list(smoke_blockers)
    if missing_assignments: pilot_blockers.append("EVERY_CANDIDATE_ASSET_NEEDS_EXPLICIT_TRAIN_VAL_TEST_OR_EXCLUDE_ASSIGNMENT")
    if split_evidence_errors: pilot_blockers.append("SPLIT_ASSIGNMENT_MISSING_EVIDENCE")
    if val_independence_errors: pilot_blockers.append("VALIDATION_INDEPENDENCE_NOT_HUMAN_VERIFIED")
    if counts["train"] < 30: pilot_blockers.append("TRAIN_IMAGE_MINIMUM_NOT_MET_30")
    if counts["val"] < 10: pilot_blockers.append("VALIDATION_IMAGE_MINIMUM_NOT_MET_10")
    if family_leaks: pilot_blockers.append("VERIFIED_SOURCE_FAMILY_CROSSES_SPLITS")
    if sha_cross_split: pilot_blockers.append("EXACT_SHA256_CROSSES_SPLITS")
    if phash_split_pairs: pilot_blockers.append("KNOWN_PHASH_CANDIDATE_PRESENT_IN_ASSIGNED_SPLITS")
    pilot_ready = not pilot_blockers
    pilot_warnings = []
    if known_family_unverified:
        pilot_warnings.append(f"SOURCE_FAMILY_UNVERIFIED_FOR_{len(family_evidence_warnings)}_ASSETS; pilot is limited and must not claim family-independent generalization")
    if duplicate_sha_pairs:
        pilot_warnings.append("EXACT_DUPLICATES_EXIST_WITHIN_CANDIDATE; check whether they are confined to one split or excluded")
    if not counts["test"]:
        pilot_warnings.append("NO_TEST_SET; pilot is for iteration only and is not formal evaluation")

    eval_blockers = list(pilot_blockers)
    if not pilot_ready: pass
    if counts["test"] < 50: eval_blockers.append("TEST_IMAGE_MINIMUM_NOT_MET_50")
    if source_families_by_split["train"] < 3 or source_families_by_split["val"] < 2 or source_families_by_split["test"] < 10:
        eval_blockers.append("VERIFIED_SOURCE_FAMILY_MINIMUMS_NOT_MET")
    if known_family_unverified: eval_blockers.append("SOURCE_FAMILY_OR_PROVENANCE_UNVERIFIED")
    family_overlap = ((families["train"] & families["val"]) | (families["train"] & families["test"]) | (families["val"] & families["test"]))
    if family_overlap: eval_blockers.append("SOURCE_FAMILIES_NOT_DISJOINT")
    evaluation_ready = not eval_blockers

    if evaluation_ready:
        status = "EVALUATION_READY"
    elif pilot_ready:
        status = "PILOT_READY"
    elif smoke_ready:
        status = "SMOKE_TEST_READY"
    else:
        status = "BLOCKED"
    result = {
        "status": status,
        "readiness": {
            "SMOKE_TEST_READY": {"ready": smoke_ready, "blockers": smoke_blockers,
                "scope": "Pipeline smoke only; no generalization or accuracy conclusion."},
            "PILOT_READY": {"ready": pilot_ready, "blockers": pilot_blockers, "warnings": pilot_warnings,
                "scope": "Training iteration with manually evidenced independent validation; unknown source families are explicitly warned."},
            "EVALUATION_READY": {"ready": evaluation_ready, "blockers": eval_blockers,
                "scope": "Human-verified independent test with verified provenance/families and no split leakage."}},
        "reviewed_polygons": reviewed_polygons, "queue_polygons": len(queue),
        "human_confirmed_green_apple_polygons": verified_green_polygons,
        "ai_assisted_auto_approved_polygons": ai_approved_polygons,
        "human_reviewed_candidate_polygons": human_reviewed_candidate_polygons,
        "candidate_review_basis": "human review events and/or explicitly AI_ASSISTED assessments; AI assessments never count as human verified",
        "candidate_images": len(manifest), "images_by_split": counts, "polygons_by_split": polygon_counts,
        "verified_source_families_by_split": source_families_by_split,
        "source_family_unverified_assets": family_evidence_warnings,
        "candidate_review_errors": review_errors, "image_integrity_errors": image_errors, "mask_errors": mask_errors,
        "source_test_assets_forbidden_from_training": source_test_training_assets,
        "unassigned_or_invalid_assignment_asset_ids": missing_assignments,
        "split_evidence_missing_asset_ids": split_evidence_errors,
        "validation_independence_missing_asset_ids": val_independence_errors,
        "verified_families_crossing_splits": family_leaks,
        "sha256_hashes_crossing_splits": sha_cross_split,
        "duplicate_sha256_extra_images_in_candidate": duplicate_sha_pairs,
        "known_phash_candidate_assets_in_assigned_splits": phash_split_pairs,
        "pilot_thresholds": {"train_images_min": 30, "validation_images_min": 10,
            "validation_independence_evidence_required": True, "source_family_id_required": False,
            "known_duplicate_or_leakage_between_splits_allowed": False},
        "evaluation_thresholds": {"test_images_min": 50, "verified_families_min": {"train": 3, "val": 2, "test": 10},
            "source_family_and_provenance_evidence_required": True, "test_masks_human_reviewed": True},
        "policy": "The checker never assigns splits or source families. A pilot without verified family IDs requires explicit evidence that validation is independent; status carries a warning. Evaluation requires verified family/provenance evidence."}
    out = args.output.expanduser().resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
